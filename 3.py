print("lesson 3 for loops and iterations")

# for loop example
print("for loop example one to print numbers from 1 to 10")
for i in range(1, 11):
    print(i)

print("for loop example two to print numbers from 10 to 1")
for i in range(10, 0, -1):
    print(i)


# while loop example
print("while loop example to print numbers from 10 to 1")
i = 10
while i >= 1:
    print(i)
    i -= 1